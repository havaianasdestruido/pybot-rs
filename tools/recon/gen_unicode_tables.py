#!/usr/bin/env python3
"""Generate Rust tables for the Unicode operations used in Fase 2.

Uses the host CPython ``unicodedata`` as a development-time source only. The resulting Rust
file is checked in and the program never imports Python or reads Unicode data at runtime.
"""
from pathlib import Path
import sys
import unicodedata

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "unicode_tables.rs"


def rust_string(value: str) -> str:
    return '"' + ''.join(f"\\u{{{ord(ch):x}}}" for ch in value) + '"'


def main() -> None:
    case = []
    nfkd_fold = []
    marks = []
    decimal_starts = []
    word_ranges = []
    last_decimal = None
    run_start = None
    word_start = None
    for cp in range(0x110000):
        char = chr(cp)
        folded = char.casefold()
        if folded != char:
            case.append((cp, folded))
        category = unicodedata.category(char)
        if category[0] in "LN":
            if word_start is None:
                word_start = cp
        elif word_start is not None:
            word_ranges.append((word_start, cp - 1))
            word_start = None
        if unicodedata.combining(char):
            marks.append(cp)
        if category == "Nd":
            if last_decimal is None or cp != last_decimal + 1:
                run_start = cp
                decimal_starts.append(cp)
            elif run_start is not None and (cp - run_start) % 10 == 0:
                decimal_starts.append(cp)
            last_decimal = cp
        decomposed = unicodedata.normalize("NFKD", char)
        folded = ''.join(c for c in decomposed if not unicodedata.combining(c)).casefold()
        folded = ''.join(c for c in folded if not unicodedata.combining(c))
        if folded != char.casefold():
            nfkd_fold.append((cp, folded))
    if word_start is not None:
        word_ranges.append((word_start, 0x10ffff))
    lines = [
        "//! Generated by `tools/recon/gen_unicode_tables.py`; do not hand-edit.",
        f"//! Python Unicode database version: {unicodedata.unidata_version}.",
        "pub const UNICODE_VERSION: &str = " + rust_string(unicodedata.unidata_version) + ";",
        "pub static CASE_FOLD: &[(u32, &str)] = &[",
    ]
    lines.extend(f"    (0x{cp:x}, {rust_string(value)})," for cp, value in case)
    lines.extend(["];", "pub static NFKD_FOLD: &[(u32, &str)] = &["])
    lines.extend(f"    (0x{cp:x}, {rust_string(value)})," for cp, value in nfkd_fold)
    lines.extend(["];", "pub static COMBINING_MARKS: &[u32] = &["])
    lines.extend(f"    0x{cp:x}," for cp in marks)
    lines.extend(["];", "pub static DECIMAL_DIGIT_STARTS: &[u32] = &["])
    lines.extend(f"    0x{cp:x}," for cp in decimal_starts)
    lines.extend(["];", "pub static ALNUM_RANGES: &[(u32, u32)] = &["])
    lines.extend(f"    (0x{start:x}, 0x{end:x})," for start, end in word_ranges)
    lines.extend(["];", ""])
    rendered = "\n".join(lines)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"{OUT.relative_to(ROOT)} is stale; regenerate with {Path(__file__).relative_to(ROOT)}")
        print(f"verified {OUT.relative_to(ROOT)}: {len(case)} case folds, {len(nfkd_fold)} NFKD folds, {len(marks)} marks, {len(decimal_starts)} decimal runs, {len(word_ranges)} alphanumeric ranges ({unicodedata.unidata_version})")
    else:
        OUT.write_text(rendered, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}: {len(case)} case folds, {len(nfkd_fold)} NFKD folds, {len(marks)} marks, {len(decimal_starts)} decimal runs, {len(word_ranges)} alphanumeric ranges ({unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
